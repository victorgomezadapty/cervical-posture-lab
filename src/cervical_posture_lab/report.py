def _max_shift(prim: pd.DataFrame, sens: pd.DataFrame) -> float:
    m = sens.merge(prim[["position", "model", "estimate"]], on=["position", "model"], suffixes=("", "_mean"))
    return float((m["estimate"] - m["estimate_mean"]).abs().max())
